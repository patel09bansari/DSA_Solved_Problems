import java.util.Scanner;

class GFG {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int n = sc.nextInt();
        
        // Loop from 0 to n-1 to print "GFG "
        for (int i = 0; i < n; i++) {
            System.out.print("GFG ");
        }
    }
}